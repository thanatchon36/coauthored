import pytest

from coauthored.policy.classify import classify


@pytest.mark.parametrize(
    "text,expected",
    [
        ("We welcome contributions. Run the tests first.", "silent"),
        ("Do not submit AI-generated code. It will be closed.", "bans"),
        ("Contributions generated by LLMs are not accepted.", "bans"),
        ("If you used an AI tool, you must disclose it in the PR description.", "requires_disclosure"),
        ("Please mention any use of Copilot or ChatGPT in your PR.", "requires_disclosure"),
        ("Add an Assisted-by: trailer when a tool helped.", "requires_disclosure"),
        ("We use AI to triage issues.", "mentions"),
        (
            "AI is fine. Contributions generated by LLMs are not accepted without review... "
            "Do not submit AI slop.",
            "bans",
        ),
    ],
)
def test_classes(text: str, expected: str) -> None:
    assert classify({"CONTRIBUTING.md": text}).cls == expected


def test_agents_md_is_config_not_policy() -> None:
    r = classify({"AGENTS.md": "You are an AI agent. Do not use AI to write tests."})
    assert r.cls == "silent" and r.agent_config


def test_quote_and_source() -> None:
    r = classify({".github/PULL_REQUEST_TEMPLATE.md": "- [ ] I disclosed any AI assistance."})
    assert r.cls == "requires_disclosure" and r.source.endswith("PULL_REQUEST_TEMPLATE.md")
    assert "AI" in r.quote
